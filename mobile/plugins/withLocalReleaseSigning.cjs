const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs/promises');
const path = require('node:path');

const BEGIN = '// @generated begin ochi-local-release-signing';
const END = '// @generated end ochi-local-release-signing';
const SCRIPT_NAME = 'ochi-release-signing.gradle';

const releaseSigningGradle = String.raw`// Generated by plugins/withLocalReleaseSigning.cjs. Do not store credentials here.
abstract class OchiSigningBuildFeatures {
    @javax.inject.Inject
    abstract org.gradle.api.configuration.BuildFeatures getBuildFeatures()
}
def ochiConfigurationCacheActive = objects.newInstance(OchiSigningBuildFeatures).buildFeatures.configurationCache.active.get()
def ochiSigningInput = { String propertyName, String environmentName ->
    providers.gradleProperty(propertyName).orElse(providers.environmentVariable(environmentName)).orNull
}
def ochiSigningInputs = [
    storePath: ochiSigningInput('ochi.android.keystorePath', 'OCHI_ANDROID_KEYSTORE_PATH'),
    keyAlias: ochiSigningInput('ochi.android.keyAlias', 'OCHI_ANDROID_KEY_ALIAS'),
    storePassword: ochiSigningInput('ochi.android.keystorePassword', 'OCHI_ANDROID_KEYSTORE_PASSWORD'),
    keyPassword: ochiSigningInput('ochi.android.keyPassword', 'OCHI_ANDROID_KEY_PASSWORD'),
]
def ochiKeystoreFile = ochiSigningInputs.storePath ? new File(ochiSigningInputs.storePath) : null
def ochiAppProject = project

// This checkout contains mobile/android; the actual key must be outside the whole checkout.
def ochiCheckoutRoot = rootProject.projectDir.parentFile.parentFile.canonicalFile

android {
    signingConfigs {
        ochiRelease {
            storeFile = ochiKeystoreFile
            storePassword = ochiSigningInputs.storePassword
            keyAlias = ochiSigningInputs.keyAlias
            keyPassword = ochiSigningInputs.keyPassword
        }
    }
    buildTypes {
        release {
            signingConfig = signingConfigs.ochiRelease
        }
    }
}

// Check output/signing tasks in the resolved graph; compile/lint alone do not need a key.
gradle.taskGraph.whenReady { graph ->
    if (!graph.allTasks.any { task ->
        task.project == ochiAppProject && (
            task.name ==~ /(?i)^(assemble|bundle|package|validateSigning).*release$/ ||
            task.name ==~ /(?i)^(sign|package).*releaseBundle$/
        )
    }) {
        return
    }
    // Cached graphs skip whenReady; distribution must revalidate the owner identity every time.
    if (ochiConfigurationCacheActive) {
        throw new GradleException('Release signing blocked: use --no-configuration-cache to revalidate the owner signing inputs.')
    }
    def missing = [
        storePath: 'OCHI_ANDROID_KEYSTORE_PATH / ochi.android.keystorePath',
        keyAlias: 'OCHI_ANDROID_KEY_ALIAS / ochi.android.keyAlias',
        storePassword: 'OCHI_ANDROID_KEYSTORE_PASSWORD / ochi.android.keystorePassword',
        keyPassword: 'OCHI_ANDROID_KEY_PASSWORD / ochi.android.keyPassword',
    ].findAll { key, label -> ochiSigningInputs[key] == null || ochiSigningInputs[key].isEmpty() }.values()
    if (!missing.isEmpty()) {
        throw new GradleException('Release signing blocked. Configure these external signing inputs: ' + missing.join(', '))
    }
    if (!ochiKeystoreFile.isAbsolute()) {
        throw new GradleException('Release signing blocked: the owner keystore path must be absolute.')
    }
    def canonicalKeystore = ochiKeystoreFile.canonicalFile
    if (canonicalKeystore.toPath().startsWith(ochiCheckoutRoot.toPath())) {
        throw new GradleException('Release signing blocked: keep the owner keystore outside this checkout.')
    }
    if (!canonicalKeystore.isFile()) {
        throw new GradleException('Release signing blocked: the configured owner keystore is not a regular file.')
    }
    if (ochiSigningInputs.keyAlias.equalsIgnoreCase('androiddebugkey')) {
        throw new GradleException('Release signing blocked: the Android debug key is not a release identity.')
    }
    if (android.buildTypes.release.signingConfig != android.signingConfigs.ochiRelease) {
        throw new GradleException('Release signing blocked: another Gradle script replaced the owner signing configuration.')
    }
}
`;

function applyLocalReleaseSigning(contents) {
  const blocks = new RegExp(`${BEGIN}[^]*?${END}\\r?\\n?`, 'g');
  const unmanaged = contents.replace(blocks, '');
  if (unmanaged.includes(BEGIN) || unmanaged.includes(END)) {
    throw new Error('Cannot update an incomplete Ochi signing block in app/build.gradle.');
  }
  return `${unmanaged.trimEnd()}\n\n${BEGIN}\napply from: "./${SCRIPT_NAME}"\n${END}\n`;
}

async function writeSigningScript(platformProjectRoot) {
  const target = path.join(platformProjectRoot, 'app', SCRIPT_NAME);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, releaseSigningGradle, 'utf8');
}

function withLocalReleaseSigning(config) {
  config = withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('Ochi local release signing requires the Expo Groovy app/build.gradle template.');
    }
    mod.modResults.contents = applyLocalReleaseSigning(mod.modResults.contents);
    return mod;
  });
  return withDangerousMod(config, ['android', async (mod) => {
    await writeSigningScript(mod.modRequest.platformProjectRoot);
    return mod;
  }]);
}

module.exports = withLocalReleaseSigning;
module.exports.applyLocalReleaseSigning = applyLocalReleaseSigning;
module.exports.writeSigningScript = writeSigningScript;
module.exports.releaseSigningGradle = releaseSigningGradle;
